import fs from 'node:fs';
import path from 'node:path';
import crypto from 'node:crypto';
import { execFileSync } from 'node:child_process';
import JSZip from 'jszip';

const root = process.cwd();
const output = path.resolve(root, '../entrega-final');
if (path.basename(root) !== 'control-de-bolsas' || path.basename(output) !== 'entrega-final') throw new Error('Unexpected workspace');
const sha = data => crypto.createHash('sha256').update(data).digest('hex');
const version = JSON.parse(fs.readFileSync('package.json')).version;
const sourceCommit = execFileSync('git', ['rev-parse', 'HEAD'], { encoding: 'utf8' }).trim();
fs.mkdirSync(output, { recursive: true });
const release = { version, sourceCommit, indexSha256: sha(fs.readFileSync('dist/index.html')), createdAt: new Date().toISOString() };
if (process.argv.includes('--manifest')) {
  fs.writeFileSync('dist/release.json', JSON.stringify(release, null, 2));
  fs.writeFileSync(path.join(output, 'release.json'), JSON.stringify(release, null, 2));
  console.log(JSON.stringify(release));
} else {
  const published = JSON.parse(fs.readFileSync('dist/release.json'));
  if (published.sourceCommit !== sourceCommit) throw new Error('Build does not match current commit');
  const bundle = path.join(output, 'control-bolsas.bundle');
  execFileSync('git', ['bundle', 'create', bundle, '--all']);
  execFileSync('git', ['bundle', 'verify', bundle], { stdio: 'pipe' });
  const zip = new JSZip();
  for (const file of execFileSync('git', ['ls-files', '-z'], { encoding: 'utf8' }).split('\0').filter(Boolean)) {
    zip.file('codigo/' + file, fs.readFileSync(file));
  }
  const addDirectory = (source, prefix) => {
    for (const entry of fs.readdirSync(source, { withFileTypes: true })) {
      const file = path.join(source, entry.name), name = prefix + '/' + entry.name;
      if (entry.isDirectory()) addDirectory(file, name); else zip.file(name, fs.readFileSync(file));
    }
  };
  addDirectory('dist', 'dist'); addDirectory('functions/lib', 'functions/lib');
  zip.file('control-bolsas.bundle', fs.readFileSync(bundle));
  for (const file of ['verification-tests.log', 'verification-build.log', 'verification-lint.log']) zip.file('verificacion/' + file, fs.readFileSync(file));
  const delivery = { ...published, git: { branch: 'main', tag: 'v' + version, repository: 'https://github.com/pacoiglesias/control-de-bolsas' }, verification: { testsPassed: 389, testsSkippedRequiringEmulator: 7, build: 'passed', lint: 'passed' }, databaseExportIncluded: false };
  zip.file('ENTREGA.json', JSON.stringify(delivery, null, 2));
  zip.file('LEEME.txt', 'Ver codigo/docs/ENTREGA_V9_12_0.md. Respaldo de software e historial Git; no contiene credenciales privadas ni exportacion de Firestore.');
  for (const file of ['deploy.log', 'verificacion-publicacion.json']) if (fs.existsSync(path.join(output, file))) zip.file('verificacion/' + file, fs.readFileSync(path.join(output, file)));
  const bytes = await zip.generateAsync({ type: 'nodebuffer', compression: 'DEFLATE', compressionOptions: { level: 6 } });
  const archive = path.join(output, 'control-bolsas-v' + version + '.zip');
  fs.writeFileSync(archive, bytes);
  const verified = await JSZip.loadAsync(fs.readFileSync(archive), { checkCRC32: true });
  if (sha(await verified.file('control-bolsas.bundle').async('nodebuffer')) !== sha(fs.readFileSync(bundle))) throw new Error('Bundle verification failed');
  fs.writeFileSync(archive + '.sha256', sha(bytes));
  fs.writeFileSync(path.join(output, 'ENTREGA.json'), JSON.stringify(delivery, null, 2));
  fs.unlinkSync(bundle);
  // Retire only release archives generated by this workflow, after the new package verifies.
  for (const file of fs.readdirSync(output)) {
    if (/^control-bolsas-v[\d.]+\.zip(?:\.sha256)?$/.test(file) && !file.startsWith('control-bolsas-v' + version + '.zip')) {
      const target = path.resolve(output, file);
      if (path.dirname(target) !== output) throw new Error('Unsafe archive path');
      fs.unlinkSync(target);
    }
  }
  console.log(JSON.stringify({ archive, bytes: bytes.length, sha256: sha(bytes), verified: true, sourceCommit }));
}
